"""Fast metadata index query probe for asset-partner.

Searches across the append-only JSONL ledger generated by scan_storage.py in <= 3 seconds.
Can match keywords, extensions, min-size, and temperature quadrants (Q1-Q4).
"""

from __future__ import annotations

import argparse
import json
import time
from pathlib import Path


def search_ledger(ledger_file: Path, query: str = "", ext: str = "", min_size_mb: float = 0.0, quadrant: str = "") -> dict:
    start_time = time.time()
    results = []
    total_scanned = 0
    total_bytes_matched = 0

    if not ledger_file.exists():
        return {
            "error": f"Ledger file not found: {ledger_file}",
            "latency_seconds": round(time.time() - start_time, 4),
            "results": [],
        }

    q_lower = query.lower() if query else ""
    ext_lower = ext.lower().lstrip(".") if ext else ""
    min_bytes = int(min_size_mb * 1024 * 1024)

    with open(ledger_file, "r", encoding="utf-8", errors="replace") as fh:
        for line in fh:
            line = line.strip()
            if not line:
                continue
            total_scanned += 1
            try:
                rec = json.loads(line)
            except Exception:
                continue

            path_str = rec.get("p", "")
            size = rec.get("s", 0)
            file_ext = rec.get("e", "").lower().lstrip(".")

            if q_lower and q_lower not in path_str.lower():
                continue
            if ext_lower and file_ext != ext_lower:
                continue
            if size < min_bytes:
                continue

            # Quadrant heuristic
            file_q = "Q3" # default hot flow
            if any(k in path_str for k in ["/Documents/", "Codex", ".obsidian", ".git", "keychain", "id_rsa"]):
                file_q = "Q1"
            elif any(file_ext in ["nsz", "nsp", "iso", "dmg", "pkg", "zip", "tar", "gz"] or size > 500 * 1024 * 1024 for _ in [1]):
                file_q = "Q2"
            elif any(k in path_str for k in ["node_modules", ".cache", "DerivedData", ".tmp"]):
                file_q = "Q4"

            if quadrant and file_q != quadrant.upper():
                continue

            results.append({
                "path": path_str,
                "size_bytes": size,
                "size_human": f"{round(size / (1024*1024), 2)} MB",
                "modified": rec.get("m"),
                "quadrant": file_q,
                "dataless": rec.get("dl", False),
            })
            total_bytes_matched += size

    latency = round(time.time() - start_time, 4)
    # Sort by size descending
    results.sort(key=lambda x: x["size_bytes"], reverse=True)

    return {
        "ledger": str(ledger_file),
        "query": query,
        "total_records_scanned": total_scanned,
        "matched_count": len(results),
        "total_matched_bytes": total_bytes_matched,
        "total_matched_mb": round(total_bytes_matched / (1024 * 1024), 2),
        "latency_seconds": latency,
        "latency_target_met": latency <= 3.0,
        "top_results": results[:20],
    }


def main() -> int:
    ap = argparse.ArgumentParser(description="Fast ledger metadata search probe")
    ap.add_argument("--ledger", required=True, help="Path to latest scan-*.jsonl ledger")
    ap.add_argument("--query", default="", help="Keyword to search in path")
    ap.add_argument("--ext", default="", help="Filter by file extension")
    ap.add_argument("--min-mb", type=float, default=0.0, help="Minimum file size in MB")
    ap.add_argument("--quadrant", choices=["Q1", "Q2", "Q3", "Q4", ""], default="", help="Filter by quadrant")
    args = ap.parse_args()

    res = search_ledger(Path(args.ledger), args.query, args.ext, args.min_mb, args.quadrant)
    print(json.dumps(res, ensure_ascii=False, indent=2))
    return 0


if __name__ == "__main__":
    main()
